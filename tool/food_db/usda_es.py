def translate(description: str) -> str | None:
    """Translate a full USDA description to Spanish.

    Returns None if any segment is missing from SEGMENTS or the result is empty.
    """
    parts = []
    for segment in description.split(","):
        key = segment.strip().lower()
        if key not in SEGMENTS:
            return None
        translated = SEGMENTS[key].strip()
        if translated:
            parts.append(translated)
    result = ", ".join(parts)
    while "  " in result:
        result = result.replace("  ", " ")
    result = result.strip()
    if not result:
        return None
    return result[0].upper() + result[1:]
